"""
2. BASIC OPERATIONS - Variables, Addition, and Concatenation
Learning: How to declare variable, add, concatenate and print the result
"""

# 2.1 Add two numbers
print("=== 2.1 Add Two Numbers ===")
a = 10
b = 220
c = a + b
print(a, " + ", b, " --> ", c)

# 2.2 Concatenate two strings
print("\n=== 2.2 Concatenate Two Strings ===")
a = "Bhagat"
b = " Singh"
c = a + b
print(a, " + ", b, " --> ", c)

# 2.3 Concatenate string with number
print("\n=== 2.3 Concatenate String with Number ===")
a = "Bhagat"
b = 100
c = a + str(b)
print(a, " + ", b, " --> ", c)
